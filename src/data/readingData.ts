export function isAnswerMatch(userInput: string, expectedAnswer: string): boolean {
  const cleanUser = (userInput || '').trim().toLowerCase().replace(/^£|\$$/g, '').trim();
  const cleanExpected = (expectedAnswer || '').trim().toLowerCase();
  if (!cleanUser) return false;
  if (cleanUser === cleanExpected) return true;
  if (NUMBER_WORD_MAP[cleanExpected] && cleanUser === NUMBER_WORD_MAP[cleanExpected]) return true;
  const reverseEntry = Object.entries(NUMBER_WORD_MAP).find(([, word]) => word === cleanExpected);
  if (reverseEntry && cleanUser === reverseEntry[0]) return true;
  return false;
}

export function calculateReadingBand(
  correctCount: number,
  totalQuestions: number,
  examType: 'academic' | 'general'
): number {
  if (correctCount <= 0) return 0;
  const scaledRaw = Math.round((correctCount / Math.max(totalQuestions, 1)) * 40);
  const clamped = Math.min(40, Math.max(4, scaledRaw));
  const table = examType === 'general' ? GENERAL_READING_CONVERSION : ACADEMIC_READING_CONVERSION;
  return table[clamped] || (clamped >= 35 ? 8.0 : clamped >= 27 ? 6.5 : 4.0);
}

